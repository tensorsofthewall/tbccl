#!/usr/bin/env python3
"""Writes the B4 presets (PyTorch communication and DDP over torch-tbccl) next to this file. Run from the repository root:  python3 benchmarks/suite/configs/generate_b4.py

The presets are plain YAML with placeholders for the real addresses, paths and launcher (a git-ignored overlay fills them). Keeping the matrix in a generator documents
exactly which configurations exist and why, and keeps the A/B/B/A interleaving of native and framework points reproducible.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAIRS = {  # torch device pairing -> (memory_backend map for torch points, the native tensor-transfer backends of the SAME memory kinds)
    "cpu-cpu": ({"host-a": "host", "host-b": "host"}, {"host-a": "host", "host-b": "host"}),
    "cuda-cpu": ({"host-a": "cuda", "host-b": "host"}, {"host-a": "cuda-pinned", "host-b": "host"}),
    "cpu-mps": ({"host-a": "host", "host-b": "mps"}, {"host-a": "host", "host-b": "metal-shared"}),
    "cuda-mps": ({"host-a": "cuda", "host-b": "mps"}, {"host-a": "cuda-pinned", "host-b": "metal-shared"}),
}
SIZES = [4096, 16384, 65536, 262144, 1048576, 4194304, 16777216]
SHORT = [64, 1024]
ITER = {4096: 100, 16384: 100, 65536: 100, 262144: 100, 1048576: 100, 4194304: 50, 16777216: 30, 64: 100, 1024: 100}


def mb(m):
    return "{" + ", ".join(f"{h}: {b}" for h, b in m.items()) + "}"


HEAD = '''# B4 preset: {desc}
# Physical (Thunderbolt) campaign: PyTorch over torch-tbccl (and Gloo as a CPU baseline) between a Linux host (host-a: CPU, CUDA) and a macOS host (host-b: CPU, MPS).
# Real addresses, paths, the torch interpreter and the launcher live in a git-ignored overlay; this file holds the workload matrix and the safety limits. Run `doctor --probe --allow-physical`
# and `--dry-run` first, then run tier by tier with --allow-physical. Results are local and git-ignored; performance numbers are never CI gates. Generated by generate_b4.py.
schema: tbccl-bench-config/1
name: {name}
description: "{desc}"
defaults:
  warmup: {warmup}
  iterations: 100
  repetitions: {reps}
  timeout_s: {timeout}
  startup_wait_s: 90
  lease_s: 30
  term_grace_s: 3
  port_range: [<PORT_RANGE_START>, <PORT_RANGE_END>]
  failure_policy: {{on_failure: abort_run}}
  provenance: {{require_same_version: true, require_stamped: true}}
  health: {{strict: true, snapshot_each_point: true, max_load_fraction: 0.9}}
limits:
  max_processes: 2
  max_point_bytes: 8589934592     # 8 GiB per repetition
  max_total_bytes: {total}
  max_campaign_s: {campaign}
topology:
  kind: direct-link
  interconnect: thunderbolt4-ip      # a label for reports; TBCCL's transport is TCP over IPv4, never RDMA
  transport: tcp
  physical: true
hosts:
  host-a:                            # the machine the suite runs on
    launcher: {{kind: local}}
    address: <HOST_A_LINK_ADDRESS>
    interface: <HOST_A_LINK_INTERFACE>
    interfaces: {{link: <HOST_A_LINK_ADDRESS>}}
    executables_dir: <HOST_A_BUILD_DIR>
    executables: {{torch_python: <HOST_A_TORCH_PYTHON>}}
    health_snapshot: true
    expect: {{mtu: <EXPECTED_MTU>}}
  host-b:                            # reached through a management-path launcher (never the data link)
    launcher: {{kind: prefix, argv: ["<REMOTE_LAUNCH_PREFIX>", "<REMOTE_HOST_NAME>"], shell_join: true}}
    python: <HOST_B_PYTHON>
    address: <HOST_B_LINK_ADDRESS>
    interface: <HOST_B_LINK_INTERFACE>
    interfaces: {{link: <HOST_B_LINK_ADDRESS>}}
    management_address: <HOST_B_MANAGEMENT_ADDRESS>   # checked: the controller must reach it through a different interface than the data link
    executables_dir: <HOST_B_BUILD_DIR>
    executables: {{torch_python: <HOST_B_TORCH_PYTHON>, torch_bench_dir: <HOST_B_TORCH_BENCH_DIR>}}
    health_script: <HOST_B_REPOSITORY>/scripts/tb4_health_snapshot.py
    expect: {{mtu: <EXPECTED_MTU>}}
ranks:
  - {{rank: 0, host: host-a, memory_backend: host, interface: link}}
  - {{rank: 1, host: host-b, memory_backend: host, interface: link}}
workloads:
'''


def wl(name, bench, ops, size, mem, src=None, opts=None, extra=""):
    o = f"operations: [{', '.join(ops)}]" if len(ops) > 1 else f"operation: {ops[0]}"
    s = f", source_ranks: {src}" if src is not None else ""
    op = f", options: {{{', '.join(f'{k}: {v}' for k, v in opts.items())}}}" if opts else ""
    return f"  - {{name: {name}, benchmark: {bench}, {o}, sizes: [{size}], memory_backend: {mb(mem)}{s}, orientations: [forward]{op}{extra}}}\n"


def write(fname, **kw):
    kw.setdefault("reps", 3)
    kw.setdefault("warmup", 20)
    kw.setdefault("timeout", 300)
    kw.setdefault("total", 214748364800)
    kw.setdefault("campaign", 7200)
    body = kw.pop("body")
    (HERE / fname).write_text(HEAD.format(**kw) + body)


def iters(size, extra=None):
    d = {"iterations": ITER[size]}
    return d


def with_iter(line, size):  # per-workload iteration count (fewer for the large payloads)
    return line[:-2] + f", iterations: {ITER[size]}}}\n"


# ---- Tier 0: validation
body = ""
for pair, (tmem, _) in PAIRS.items():
    for op, src in (("all_reduce", None), ("broadcast", [0, 1]), ("all_gather", None)):
        body += wl(f"v-coll-{pair}-{op}", "torch_collectives", [op], 4096, tmem, src)
    body += wl(f"v-p2p-{pair}", "torch_p2p", ["p2p_ack"], 4096, tmem, [0, 1])
    body += wl(f"v-async-{pair}", "torch_async", ["all_reduce_async"], 4096, tmem)
    body += wl(f"v-isend-{pair}", "torch_async", ["isend_irecv_ack"], 4096, tmem, [0, 1])
    body += wl(f"v-ddp-{pair}", "torch_ddp", ["train"], 2 * (256 * 256 + 256) * 4, tmem, None, {"layers": 2, "width": 256, "batch": 16, "tag": "tiny", "steps": 8})
write("b4-validation.yaml", name="b4-validation", desc="PyTorch correctness smoke over the link: every device pairing, every operation family, 4 KiB, one repetition", reps=1, timeout=180, total=2147483648, campaign=1800, warmup=10, body=body)

# ---- Tier 1: collectives and p2p on torch-tbccl
body = ""
for pair, (tmem, _) in PAIRS.items():
    for size in SIZES:
        for op, src in (("all_reduce", None), ("broadcast", [0, 1]), ("all_gather", None)):
            body += with_iter(wl(f"c-{pair}-{op}-{size}", "torch_collectives", [op], size, tmem, src), size)
        body += with_iter(wl(f"p-{pair}-{size}", "torch_p2p", ["p2p_ack"], size, tmem, [0, 1]), size)
for size in SIZES:
    body += with_iter(wl(f"r-cpu-cpu-rtt-{size}", "torch_p2p", ["p2p_rtt"], size, PAIRS["cpu-cpu"][0], [0]), size)
for size in SHORT:
    for pair in ("cpu-cpu", "cuda-mps"):
        for op in ("all_reduce",):
            body += with_iter(wl(f"s-{pair}-{op}-{size}", "torch_collectives", [op], size, PAIRS[pair][0]), size)
        body += with_iter(wl(f"s-{pair}-p2p-{size}", "torch_p2p", ["p2p_ack"], size, PAIRS[pair][0], [0, 1]), size)
write("b4-collectives.yaml", name="b4-collectives", desc="PyTorch collectives and point-to-point over torch-tbccl: CPU/CPU, CUDA/CPU, CPU/MPS, CUDA/MPS, 4 KiB to 16 MiB plus short messages", body=body, campaign=14400)

# ---- Gloo: NOT generated. The Linux and macOS PyTorch 2.13.0 Gloo builds use different store key schemes ('0'/'1' vs 'rank_0'/'rank_1') and cannot form a group across the two hosts
#      (reproduced: both ranks wait for the other's key until the timeout), so no Gloo baseline over this link exists. See the B4 report.

# ---- async
body = ""
for pair, (tmem, _) in PAIRS.items():
    for size in SIZES:
        body += with_iter(wl(f"a-{pair}-ar-{size}", "torch_async", ["all_reduce_async"], size, tmem), size)
        body += with_iter(wl(f"a-{pair}-isend-{size}", "torch_async", ["isend_irecv_ack"], size, tmem, [0, 1]), size)
write("b4-async.yaml", name="b4-async", desc="PyTorch asynchronous communication: all_reduce(async_op=True) and isend/irecv, submission versus wait versus completion", body=body, campaign=10800)

# ---- framework overhead: native (A) versus torch-tbccl (B), interleaved A,B,B,A per block, one repetition per point
AB_SIZES = [4096, 65536, 1048576, 16777216]
BLOCKS = 3


def native_e2e(name, pair, size, src, tag):
    nm = PAIRS[pair][1]
    return (f"  - {{name: {name}, benchmark: tensor_transfer, operation: end_to_end, sizes: [{size}], memory_backend: {mb(nm)}, source_ranks: [{src}], orientations: [forward], "
            f"repetitions: 1, iterations: {ITER[size]}, options: {{tag: {tag}}}}}\n")


def native_sm(name, op, size, tag):
    return (f"  - {{name: {name}, benchmark: small_message_latency, operation: {op}, sizes: [{size}], memory_backend: {mb(PAIRS['cpu-cpu'][1])}, orientations: [forward], repetitions: 1, "
            f"iterations: {ITER[size]}, options: {{tag: {tag}}}}}\n")


def torch_one(name, bench, op, size, pair, src, tag):
    s = f", source_ranks: [{src}]" if src is not None else ""
    return (f"  - {{name: {name}, benchmark: {bench}, operation: {op}, sizes: [{size}], memory_backend: {mb(PAIRS[pair][0])}{s}, orientations: [forward], repetitions: 1, "
            f"iterations: {ITER[size]}, options: {{tag: {tag}}}}}\n")


body = ""
for block in range(1, BLOCKS + 1):
    for size in AB_SIZES:
        for pair in PAIRS:
            for src in (0, 1):
                t = f"b{block}-{pair}-s{src}"
                body += native_e2e(f"ab{block}-{pair}-{size}-s{src}-A1", pair, size, src, t + "-A1")
                body += torch_one(f"ab{block}-{pair}-{size}-s{src}-B1", "torch_p2p", "p2p_ack", size, pair, src, t + "-B1")
                body += torch_one(f"ab{block}-{pair}-{size}-s{src}-B2", "torch_p2p", "p2p_ack", size, pair, src, t + "-B2")
                body += native_e2e(f"ab{block}-{pair}-{size}-s{src}-A2", pair, size, src, t + "-A2")
        for op, nop, bench in (("all_reduce", "allreduce", "torch_collectives"), ("all_gather", "allgather", "torch_collectives")):
            t = f"b{block}-cpu-{op}"
            body += native_sm(f"ab{block}-{op}-{size}-A1", nop, size, t + "-A1")
            body += torch_one(f"ab{block}-{op}-{size}-B1", bench, op, size, "cpu-cpu", None, t + "-B1")
            body += torch_one(f"ab{block}-{op}-{size}-B2", bench, op, size, "cpu-cpu", None, t + "-B2")
            body += native_sm(f"ab{block}-{op}-{size}-A2", nop, size, t + "-A2")
        t = f"b{block}-cpu-rtt"
        body += native_sm(f"ab{block}-rtt-{size}-A1", "p2p", size, t + "-A1")
        body += torch_one(f"ab{block}-rtt-{size}-B1", "torch_p2p", "p2p_rtt", size, "cpu-cpu", 0, t + "-B1")
        body += torch_one(f"ab{block}-rtt-{size}-B2", "torch_p2p", "p2p_rtt", size, "cpu-cpu", 0, t + "-B2")
        body += native_sm(f"ab{block}-rtt-{size}-A2", "p2p", size, t + "-A2")
write("b4-framework.yaml", name="b4-framework", desc="native TBCCL versus torch-tbccl, matched hosts, direction, size, memory kind and completion semantics, interleaved A,B,B,A", reps=1, body=body, campaign=14400)

# ---- DDP
MODELS = {  # tag -> (layers, width, batch, bucket_cap_mb, why)
    "S-b64": (4, 512, 64, 25, "small model (4.2 MB of gradients), small batch: communication per step is cheap but compute is tiny, expected communication-bound on the accelerators"),
    "M-b64": (8, 1024, 64, 25, "medium model (33.6 MB of gradients), small batch: communication-heavy, a single 25 MB-capped bucket pair"),
    "M-b256": (8, 1024, 256, 25, "same model, 4x batch: more compute per byte of gradient, expected to shift towards compute-bound"),
}
body = ""
for pair, (tmem, _) in PAIRS.items():
    for tag, (L, W, Bs, cap, why) in MODELS.items():
        if tag == "M-b256" and pair not in ("cuda-mps", "cpu-cpu"):
            continue  # the compute-bound probe runs on the two pairings that bracket the compute imbalance (both CPUs; CUDA next to MPS)
        grad = L * (W * W + W) * 4
        body += f"  # {pair} {tag}: {why}\n"
        body += wl(f"d-{pair}-{tag}", "torch_ddp", ["train"], grad, tmem, None, {"layers": L, "width": W, "batch": Bs, "bucket_cap_mb": cap, "tag": f"{tag}-bk{cap}", "steps": 20})
for pair in ("cuda-mps",):
    L, W, Bs, _, _ = MODELS["M-b64"]
    grad = L * (W * W + W) * 4
    for cap in (1, 5, 100):
        body += f"  # {pair} M-b64: bucket sweep ({cap} MB cap) against the 25 MB default above\n"
        body += wl(f"d-{pair}-M-b64-bk{cap}", "torch_ddp", ["train"], grad, PAIRS[pair][0], None, {"layers": L, "width": W, "batch": Bs, "bucket_cap_mb": cap, "tag": f"M-b64-bk{cap}", "steps": 20})
write("b4-ddp.yaml", name="b4-ddp", desc="two-rank DistributedDataParallel training of a synthetic deep MLP over torch-tbccl: device pairings, model sizes, batch sizes and bucket caps", reps=3, timeout=900, warmup=3, body=body.replace("iterations: 100", "iterations: 20"), campaign=14400)

# ---- DDP, compute-heavier configurations (the first DDP preset is communication-bound everywhere: compute is 1-30 ms against steps of 9-85 ms)
BIG = {  # tag -> (layers, width, batch, steps, why)
    "S-b512": (4, 512, 512, 20, "small model, 8x batch: balances compute and the 4.2 MB gradient exchange on the accelerators"),
    "S-b2048": (4, 512, 2048, 20, "small model, 32x batch: compute-bound on the CPU ranks, still cheap on the accelerators"),
    "M-b2048": (8, 1024, 2048, 10, "medium model, large batch (103 GFLOP of forward/backward per step): compute-bound everywhere, the accelerator/CPU imbalance dominates"),
}
body = ""
for tag, (L, W, Bs, nsteps, why) in BIG.items():
    for pair, (tmem, _) in PAIRS.items():
        if tag == "S-b512" and pair == "cpu-mps":
            continue
        grad = L * (W * W + W) * 4
        body += f"  # {pair} {tag}: {why}\n"
        body += wl(f"dc-{pair}-{tag}", "torch_ddp", ["train"], grad, tmem, None, {"layers": L, "width": W, "batch": Bs, "bucket_cap_mb": 25, "tag": f"{tag}-bk25", "steps": nsteps})
write("b4-ddp-compute.yaml", name="b4-ddp-compute", desc="two-rank DDP with larger batches: balanced and compute-bound configurations, and the accelerator/CPU compute imbalance", reps=3, timeout=1800, warmup=2, body=body.replace("iterations: 100", "iterations: 20"), campaign=10800)

# ---- confirmation: 5 repetitions of the points the conclusions rest on
body = ""
for pair, (tmem, _) in PAIRS.items():
    for size in ((4096, 1048576, 16777216) if pair in ("cpu-cpu", "cuda-mps") else (4096, 1048576)):
        body += with_iter(wl(f"k-{pair}-ar-{size}", "torch_collectives", ["all_reduce"], size, tmem), size)
        body += with_iter(wl(f"k-{pair}-p2p-{size}", "torch_p2p", ["p2p_ack"], size, tmem, [0, 1]), size)
        body += with_iter(wl(f"k-{pair}-async-{size}", "torch_async", ["all_reduce_async"], size, tmem), size)
    L, W, Bs, cap, _ = MODELS["M-b64"]
    if pair not in ("cpu-cpu", "cuda-mps"):
        continue
    body += wl(f"k-{pair}-ddp-M-b64", "torch_ddp", ["train"], L * (W * W + W) * 4, tmem, None, {"layers": L, "width": W, "batch": Bs, "bucket_cap_mb": cap, "tag": f"M-b64-bk{cap}", "steps": 20})
body += wl("k-cuda-mps-ddp-M-b2048", "torch_ddp", ["train"], 8 * (1024 * 1024 + 1024) * 4, PAIRS["cuda-mps"][0], None, {"layers": 8, "width": 1024, "batch": 2048, "bucket_cap_mb": 25, "tag": "M-b2048-bk25", "steps": 10})
write("b4-confirm.yaml", name="b4-confirm", desc="five-repetition confirmation of selected collective, point-to-point, asynchronous and DDP points", reps=5, timeout=1800, warmup=5, body=body, campaign=10800)

# ---- profile (traced steps, separate from the timed phases above)
body = ""
for pair in ("cuda-cpu", "cuda-mps", "cpu-mps", "cpu-cpu"):
    L, W, Bs, cap, _ = MODELS["M-b64"]
    grad = L * (W * W + W) * 4
    body += wl(f"p-{pair}-M-b64-prof", "torch_ddp", ["train"], grad, PAIRS[pair][0], None, {"layers": L, "width": W, "batch": Bs, "bucket_cap_mb": 5, "tag": "M-b64-bk5-profile", "steps": 20, "profile": "true", "profile_steps": 20})
write("b4-profile.yaml", name="b4-profile", desc="DDP communication/compute overlap with the adapter's collective trace and GPU sampling, in loops separate from the timed ones", reps=3, timeout=900, warmup=5, body=body.replace("iterations: 100", "iterations: 20"), campaign=7200)
print("written")
