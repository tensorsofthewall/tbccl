#!/usr/bin/env python3
"""Writes the B5 presets (vLLM pipeline-parallel inference over vllm-tbccl) next to this file. Run from the repository root:  python3 benchmarks/suite/configs/generate_b5.py

The presets are plain YAML with placeholders for the real addresses, paths and launcher (a git-ignored overlay fills them). Each workload point is one engine lifecycle running an ordered list
of client phases (the vllm-tbccl provider client); the generator documents exactly which phases exist, in which order, and with which seeds. Passes over a grid are repeated and the cell order is
shuffled with a fixed seed for each pass, so slow drift (thermal state, caches) does not line up with a single cell.
"""
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAX_LEN = 4096
PROMPTS = [16, 128, 512, 1000, 2000]
REF_TOKENS = 64
CONFIGS = {  # label -> (memory_backend by host, orientation, description)
    "cuda-metal": ({"host-a": "cuda", "host-b": "metal"}, "forward", "stage 0 CUDA (Linux, API node), stage 1 Metal (Mac, headless)"),
    "metal-cuda": ({"host-a": "cuda", "host-b": "metal"}, "reverse", "stage 0 Metal (Mac, API node), stage 1 CUDA (Linux, headless)"),
    "cuda-cpu": ({"host-a": "cuda", "host-b": "host"}, "forward", "stage 0 CUDA (Linux, API node), stage 1 CPU (Mac, headless)"),
}
UTIL = {"host-a": 0.5, "host-b": 0.3}

HEAD = '''# B5 preset: {desc}
# Physical (Thunderbolt) campaign: vLLM {vllm} pipeline parallelism (PP=2, TP=1) over vllm-tbccl {tbccl} between a Linux host (host-a: CUDA) and a macOS host (host-b: Metal or CPU).
# Real addresses, paths, interpreters and the launcher live in a git-ignored overlay; this file holds the workload matrix and the safety limits. Run `doctor --probe --allow-physical`
# and `--dry-run` first, then run tier by tier with --allow-physical. Results are local and git-ignored; performance numbers are never CI gates. Generated by generate_b5.py.
schema: tbccl-bench-config/1
name: {name}
description: "{desc}"
defaults:
  repetitions: {reps}
  timeout_s: {timeout}
  startup_wait_s: 90
  lease_s: 30
  term_grace_s: 20
  port_range: [<PORT_RANGE_START>, <PORT_RANGE_END>]
  failure_policy: {{on_failure: {failure_policy}}}
  provenance: {{require_same_version: false, require_stamped: false}}
  health: {{strict: true, snapshot_each_point: true, max_load_fraction: 4.0}}
limits:
  max_processes: 8
  max_point_bytes: 8589934592
  max_total_bytes: {total}
  max_campaign_s: {campaign}
topology:
  kind: direct-link
  interconnect: thunderbolt4-ip      # a label for reports; TBCCL's transport is TCP over IPv4, never RDMA
  transport: tcp
  physical: true
hosts:
  host-a:                            # the machine the suite runs on
    launcher: {{kind: local}}
    address: <HOST_A_LINK_ADDRESS>
    interface: <HOST_A_LINK_INTERFACE>
    interfaces: {{link: <HOST_A_LINK_ADDRESS>}}
    executables: {{vllm: <HOST_A_VLLM>, vllm_python: <HOST_A_VLLM_PYTHON>, vllm_model_dir: <HOST_A_MODEL_DIR>, vllm_workload: <HOST_A_WORKLOAD>, vllm_reference: <HOST_A_REFERENCE>}}
    health_snapshot: true
    expect: {{mtu: <EXPECTED_MTU>}}
  host-b:                            # reached through a management-path launcher (never the data link)
    launcher: {{kind: prefix, argv: ["<REMOTE_LAUNCH_PREFIX>", "<REMOTE_HOST_NAME>"], shell_join: true}}
    python: <HOST_B_PYTHON>
    address: <HOST_B_LINK_ADDRESS>
    interface: <HOST_B_LINK_INTERFACE>
    interfaces: {{link: <HOST_B_LINK_ADDRESS>}}
    management_address: <HOST_B_MANAGEMENT_ADDRESS>   # checked: the controller must reach it through a different interface than the data link
    executables: {{vllm: <HOST_B_VLLM>, vllm_python: <HOST_B_VLLM_PYTHON>, vllm_model_dir: <HOST_B_MODEL_DIR>, vllm_bench_dir: <HOST_B_VLLM_BENCH_DIR>, vllm_workload: <HOST_B_WORKLOAD>, vllm_reference: <HOST_B_REFERENCE>}}
    health_script: <HOST_B_REPOSITORY>/scripts/tb4_health_snapshot.py
    expect: {{mtu: <EXPECTED_MTU>}}
'''


def j(x):
    return json.dumps(x, separators=(", ", ": "))


def ranks_block():
    return "ranks:\n  - {rank: 0, host: host-a, memory_backend: host, interface: link}\n  - {rank: 1, host: host-b, memory_backend: host, interface: link}\n"


def phase(name, kind, **kw):
    return {"name": name, "kind": kind, **kw}


def shuffled(cells, seed):
    cells = list(cells)
    random.Random(seed).shuffle(cells)
    return cells


def latency_grid(passes=3, per_cell=10, prompts=(16, 128, 512), outputs=(1, 32, 64), seed=101):
    cells = [(p, o) for p in prompts for o in outputs]
    out = []
    for k in range(passes):
        for p, o in shuffled(cells, seed + k):
            out.append(phase(f"lat-r{k + 1}-p{p}-o{o}", "rounds", prompt=f"p{p}", tokens=o, conc=1, rounds=per_cell, round_group=k + 1))
    return out


def check_phases(prefix="gate"):
    names = [f"p{n}" for n in PROMPTS]
    return [
        phase(f"{prefix}-seq", "check", cases=names, conc=1, tokens=32, scrape=False),
        phase(f"{prefix}-seq-long", "check", cases=names, conc=1, tokens=64, scrape=False),
        phase(f"{prefix}-conc12", "check", cases=names, conc=12, repeat=3, tokens=32, seed=11),
        phase(f"{prefix}-conc12-b", "check", cases=names, conc=12, repeat=3, tokens=32, seed=12),
        phase(f"{prefix}-mixed12", "check", cases=names, conc=12, repeat=3, tokens=64, random_len=True, seed=13),
        phase(f"{prefix}-stagger12", "check", cases=names, conc=12, repeat=3, tokens=32, stagger_s=0.5, seed=14),
        phase(f"{prefix}-repeat", "check", cases=names, conc=1, repeat=3, tokens=16),
        phase(f"{prefix}-cancel", "cancel", prompt="p128", tokens=400, streams=8, complete_every=4, drop_after_events=4, followup={"kind": "check", "cases": names, "conc": 1, "tokens": 32}),
    ]


def point(name, benchmark, op, config, phases, *, orientation=None, primary=None, trace=None, tag=None, timeout=None, extra=None, single_device=None, startup=600, reps=None):
    mem, ori, _ = CONFIGS[config] if config else ({"host-a": single_device} if single_device == "cuda" else {"host-b": single_device}, "forward", "")
    opts = {"dtype": "bfloat16", "max_model_len": MAX_LEN, "gpu_memory_utilization": UTIL, "startup_timeout_s": startup, "request_timeout_s": 180, "tag": tag or name, "phases": phases}
    if primary:
        opts["primary"] = primary
    if trace:
        opts["trace"] = trace
    opts.update(extra or {})
    wl = {"name": name, "benchmark": benchmark, "operation": op, "sizes": [1], "memory_backend": mem, "orientations": [orientation or ori],
          "options": opts}
    if not config:
        wl["rank_counts"] = [1]
        wl["rank_hosts"] = ["host-a" if single_device == "cuda" else "host-b"]
    if timeout:
        wl["timeout_s"] = timeout
    if reps:
        wl["repetitions"] = reps
    return wl


def write(name, desc, workloads, *, reps=1, timeout=2400, total=34359738368, campaign=21600, failure_policy="abort_run", vllm="0.31.0", tbccl="0.2.0"):
    text = HEAD.format(desc=desc, name=name, reps=reps, timeout=timeout, total=total, campaign=campaign, vllm=vllm, tbccl=tbccl, failure_policy=failure_policy) + ranks_block() + "workloads:\n"
    for wl in workloads:
        text += f"  - {j(wl)}\n"
    (HERE / f"{name}.yaml").write_text(text)
    print(name, len(workloads), "workloads")


def main():
    ref_cases = [{"name": f"p{n}", "prompt": f"p{n}", "tokens": REF_TOKENS} for n in PROMPTS]
    # Tier 0: the single-rank CUDA reference (greedy, one request at a time) and its own concurrency control
    write("b5-tier0-reference", "single-rank CUDA reference generation and the single-node concurrency control", [
        point("ref-cuda", "vllm_correctness", "gates", None, [phase("reference", "reference", cases=ref_cases, tokens=REF_TOKENS), phase("self-check", "check", cases=[f"p{n}" for n in PROMPTS], conc=1, tokens=REF_TOKENS, repeat=3)],
              single_device="cuda", primary={"phase": "self-check", "metric": "e2e"}, extra={"use_reference": False}),
    ], timeout=900, campaign=3600)
    gates = check_phases()
    write("b5-tier0-control", "single-node CUDA control: the same gates as the pipelines (bf16 batch-composition effects without any pipeline)", [
        point("control-cuda", "vllm_correctness", "gates", None, gates, single_device="cuda"),
    ], timeout=1500, campaign=3600)
    # Tier 1: startup and correctness gates of each validated pipeline
    write("b5-tier1-gates", "pipeline startup, transport proof and correctness gates for the three validated stage assignments", [
        point(f"gates-{c}", "vllm_correctness", "gates", c, [phase("warm", "warmup", prompt="p128", tokens=8, requests=3)] + gates, timeout=2700) for c in CONFIGS
    ], timeout=2700, campaign=14400)
    # Tier 2: single-request latency grids (3 interleaved passes), one point per pairing
    write("b5-tier2-latency", "single-request TTFT/TPOT/ITL/E2E: 3 prompt lengths x 3 output lengths, 3 passes, concurrency 1", [
        point(f"latency-{c}", "vllm_latency", "single_request", c, [phase("warm", "warmup", prompt="p128", tokens=8, requests=3)] + latency_grid(), primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, timeout=3000)
        for c in CONFIGS
    ], timeout=3000, campaign=18000)
    # Tier 3: concurrency 1/2/4/8/12 with a correctness gate first at every level (Tier 5 repeats it with the other stage order, Tier 6 with the CPU stage and fewer levels)
    def conc_phases(levels=(1, 2, 4, 8, 12), prompt="p128", tokens=32, passes=3, rounds=10, seed=201):
        out = [phase("warm", "warmup", prompt=prompt, tokens=8, requests=3)]
        for c in levels:
            out.append(phase(f"gate-c{c}", "check", cases=[f"p{n}" for n in PROMPTS], conc=c, repeat=2 if c > 1 else 1, tokens=32, seed=20 + c))
        for k in range(passes):
            for c in shuffled(list(levels), seed + k):
                out.append(phase(f"conc-r{k + 1}-c{c}-rounds", "rounds", prompt=prompt, tokens=tokens, conc=c, rounds=rounds, round_group=k + 1))
                out.append(phase(f"conc-r{k + 1}-c{c}-cont", "continuous", prompt=prompt, tokens=tokens, conc=c, requests=max(40, 8 * c), round_group=k + 1))
        return out

    def conc_point(c, levels=(1, 2, 4, 8, 12), passes=3, timeout=4500):
        top = levels[-1]
        return point(f"conc-{c}", "vllm_concurrency", "sweep", c, conc_phases(levels, passes=passes), primary={"phase": f"conc-r1-c{top}-rounds", "metric": "e2e"}, timeout=timeout)
    write("b5-tier3-concurrency", "throughput and latency against closed-loop concurrency (1/2/4/8/12), p128/o32, rounds and continuous loops, 3 passes; one point per stage assignment", [
        conc_point("cuda-metal"), conc_point("metal-cuda"), conc_point("cuda-cpu", levels=(1, 2, 4), passes=2, timeout=5400)], timeout=5400, campaign=28800)
    # Tier 3b: mixed lengths, open-loop arrivals and longer contexts (their own labelled workloads, never merged with the fixed-length closed loops)
    mix12 = [{"prompt": f"p{n}", "tokens": t} for n, t in ((16, 8), (128, 32), (512, 16), (1000, 32), (2000, 16), (128, 64), (16, 64), (512, 32), (128, 8), (1000, 8), (2000, 32), (16, 32))]
    def mixed_phases():
        names = [f"p{n}" for n in PROMPTS]
        out = [phase("warm", "warmup", prompt="p128", tokens=8, requests=3), phase("gate-mixed", "check", cases=names, conc=12, repeat=3, tokens=64, random_len=True, seed=31),
               phase("gate-long", "check", cases=["p1000", "p2000"], conc=4, repeat=3, tokens=32, seed=32)]
        for k in range(1, 4):
            out.append(phase(f"mix-r{k}", "rounds", mix=mix12, rounds=6, round_group=k))
        for k in range(1, 4):
            for c in (1, 4):
                out.append(phase(f"long-r{k}-c{c}-p2000", "continuous", prompt="p2000", tokens=32, conc=c, requests=max(16, 6 * c), round_group=k))
                out.append(phase(f"long-r{k}-c{c}-p1000", "continuous", prompt="p1000", tokens=32, conc=c, requests=max(16, 6 * c), round_group=k))
        for rate in (1, 2, 4):
            out.append(phase(f"open-rate{rate}", "open_loop", prompt="p128", tokens=32, rate=rate, requests=60, seed=40 + rate))
        return out
    write("b5-tier3b-mixed", "mixed-length batches, open-loop arrivals and longer contexts (p1000, p2000)", [
        point(f"mixed-{c}", "vllm_throughput", "mixed", c, mixed_phases(), primary={"phase": "mix-r1", "metric": "e2e"}, timeout=5400) for c in ("cuda-metal", "metal-cuda")], timeout=5400, campaign=21600)
    # Tier 4: prefill and decode sensitivity
    def sweep_phases(prompts=(16, 128, 512, 1000, 2000), decode=(1, 8, 32, 64, 128, 256), passes=3, rounds=8):
        out = [phase("warm", "warmup", prompt="p128", tokens=8, requests=3)]
        cells = [("pre", p, o) for p in prompts for o in (1, 8)] + [("dec", 128, o) for o in decode]
        for k in range(passes):
            for kind, p, o in shuffled(cells, 301 + k):
                out.append(phase(f"{kind}-r{k + 1}-p{p}-o{o}", "rounds", prompt=f"p{p}", tokens=o, conc=1, rounds=rounds, round_group=k + 1))
        return out
    write("b5-tier4-sweeps", "prefill sensitivity (prompt length at 1 and 8 output tokens) and decode sensitivity (output length at p128), concurrency 1", [
        point("sweeps-cuda-metal", "vllm_latency", "single_request", "cuda-metal", sweep_phases(), primary={"phase": "dec-r1-p128-o64", "metric": "tpot"}, timeout=3600),
        point("sweeps-metal-cuda", "vllm_latency", "single_request", "metal-cuda", sweep_phases(), primary={"phase": "dec-r1-p128-o64", "metric": "tpot"}, timeout=3600),
        point("sweeps-cuda-cpu", "vllm_latency", "single_request", "cuda-cpu", sweep_phases(prompts=(16, 128, 512), decode=(1, 8, 32, 64), passes=2, rounds=5), primary={"phase": "dec-r1-p128-o64", "metric": "tpot"}, timeout=5400),
    ], timeout=5400, campaign=28800)
    # Tier 7: single-node contextual baselines (same workloads, same accounting)
    base = [phase("warm", "warmup", prompt="p128", tokens=8, requests=3)] + gates[:2] + latency_grid(passes=2, seed=401) + [
        phase("conc-1-cont", "continuous", prompt="p128", tokens=32, conc=1, requests=40), phase("conc-4-cont", "continuous", prompt="p128", tokens=32, conc=4, requests=64),
        phase("conc-12-cont", "continuous", prompt="p128", tokens=32, conc=12, requests=96)]
    write("b5-tier7-baselines", "single-node contextual references: CUDA only, Metal only, Mac CPU only", [
        point("base-cuda", "vllm_pipeline", "baseline", None, base, single_device="cuda", primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, timeout=3000),
        point("base-metal", "vllm_pipeline", "baseline", None, base, single_device="metal", primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, timeout=3000),
        point("base-cpu", "vllm_pipeline", "baseline", None, base, single_device="host", primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, timeout=3000),
    ], timeout=3000, campaign=14400)

    # Tier 8 (lifecycle): failure injection, kept apart from every performance tier. Failures are the expected outcome, so the run continues after a failed point.
    longstream = [phase("warm", "warmup", prompt="p128", tokens=8, requests=2),
                  phase("long", "rounds", prompt="p128", tokens=1500, conc=1, rounds=1, request_timeout_s=45, scrape=False)]
    cyc = [phase("warm", "warmup", prompt="p128", tokens=8, requests=2), phase("seq", "check", cases=[f"p{n}" for n in (16, 128, 512)], conc=1, tokens=16),
           phase("cancel", "cancel", prompt="p128", tokens=400, streams=4, complete_every=2, drop_after_events=3, followup={"kind": "check", "cases": ["p16", "p128"], "conc": 1, "tokens": 16})]
    life = [
        point("kill-headless-worker-cuda-metal", "vllm_pipeline", "diagnostic", "cuda-metal", longstream, primary={"phase": "long", "metric": "e2e"}, extra={"fault": {"stage": 1, "delay_s": 3}}, timeout=420),
        point("kill-headless-worker-metal-cuda", "vllm_pipeline", "diagnostic", "metal-cuda", longstream, primary={"phase": "long", "metric": "e2e"}, extra={"fault": {"stage": 1, "delay_s": 3}}, timeout=420),
        point("kill-api-worker-cuda-metal", "vllm_pipeline", "diagnostic", "cuda-metal", longstream, primary={"phase": "long", "metric": "e2e"}, extra={"fault": {"stage": 0, "delay_s": 3}}, timeout=420),
        point("bad-model-cuda-metal", "vllm_startup", "startup", "cuda-metal", [phase("warm", "warmup", prompt="p16", tokens=4, requests=1)], primary={"phase": "warm", "metric": "e2e"},
              extra={"model_dir_override": "/nonexistent/model"}, startup=90, timeout=240),
        point("request-timeout-cuda-metal", "vllm_pipeline", "diagnostic", "cuda-metal", [phase("warm", "warmup", prompt="p128", tokens=8, requests=2),
              phase("tiny-timeout", "rounds", prompt="p128", tokens=400, conc=1, rounds=2, request_timeout_s=0.3, allow_failures=True, scrape=False),
              phase("after", "check", cases=["p16", "p128"], conc=1, tokens=16)], primary={"phase": "after", "metric": "e2e"}, timeout=600),
        point("cycles-cuda-metal", "vllm_startup", "startup", "cuda-metal", cyc, primary={"phase": "seq", "metric": "e2e"}, timeout=900, reps=3),
        point("cycles-metal-cuda", "vllm_startup", "startup", "metal-cuda", cyc, primary={"phase": "seq", "metric": "e2e"}, timeout=900, reps=3),
    ]
    write("b5-tier8-lifecycle", "lifecycle validation: worker loss on the headless and the API node, failed initialisation, a client request timeout, repeated engine cycles", life,
          timeout=900, campaign=14400, failure_policy="continue")

    # Tier 5b: client placement control. The API node follows the stage order, so a stage-order comparison also moves the API and the client; here the client runs on the other machine
    # (over the management LAN) so that the same cells can be compared with the local-client runs.
    def key_phases(passes=2, seed=501):
        out = [phase("warm", "warmup", prompt="p128", tokens=8, requests=3), phase("gate-seq", "check", cases=[f"p{n}" for n in (16, 128, 512)], conc=1, tokens=32, scrape=False)]
        cells = [(16, 1), (128, 32), (512, 32)]
        for k in range(passes):
            for p, o in shuffled(cells, seed + k):
                out.append(phase(f"lat-r{k + 1}-p{p}-o{o}", "rounds", prompt=f"p{p}", tokens=o, conc=1, rounds=10, round_group=k + 1))
        for k in range(passes):
            for c in shuffled([1, 4, 12], seed + 10 + k):
                out.append(phase(f"conc-r{k + 1}-c{c}-cont", "continuous", prompt="p128", tokens=32, conc=c, requests=max(40, 8 * c), round_group=k + 1))
        return out
    write("b5-tier5b-placement", "client placement control: the same cells with the client on the other machine (management LAN)", [
        point("placement-cuda-metal-remote", "vllm_pipeline", "order", "cuda-metal", key_phases(), primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, extra={"client_host": "other"}, timeout=2400),
        point("placement-metal-cuda-remote", "vllm_pipeline", "order", "metal-cuda", key_phases(), primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, extra={"client_host": "other"}, timeout=2400),
    ], timeout=2400, campaign=14400)
    # Tier 9: confirmation runs of the key cells, one new engine lifecycle per repetition, the two stage orders interleaved A,B,B,A,... (the CPU pairing separately)
    order = ["cuda-metal", "metal-cuda", "metal-cuda", "cuda-metal"] * 2 + ["cuda-metal", "metal-cuda"]
    confirm = [point(f"confirm-{c}-{i}", "vllm_pipeline", "order", c, key_phases(seed=600 + i), primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, tag=f"confirm-{c}-{i}", timeout=2400)
               for i, c in enumerate(order)]
    confirm += [point(f"confirm-cuda-cpu-{i}", "vllm_pipeline", "order", "cuda-cpu", key_phases(passes=1, seed=700 + i), primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, tag=f"confirm-cuda-cpu-{i}", timeout=3000)
                for i in range(3)]
    write("b5-tier9-confirm", "confirmation runs of the key cells: 5 independent engine lifecycles per stage order (interleaved), 3 for the CPU pairing", confirm, timeout=3000, campaign=28800)

    # Tier 8 (trace): stage-level diagnostic runs, separate from every uninstrumented run. vllm-tbccl's own trace records the pipeline transfers, the Metal / CPU stage steps are timed by
    # VLLM_TBCCL_TRACE_STEPS, and the vllm-tbccl provider hook (trace_hook) times the CUDA stage and the submissions. The traced cells repeat the confirmation cells so the overhead of tracing is measurable.
    trace_cells = key_phases(passes=1, seed=800) + [phase(f"lat-r1-p128-o{o}", "rounds", prompt="p128", tokens=o, conc=1, rounds=10, round_group=1) for o in (1, 8)]  # the o=1/8/32 TTFT step is traced explicitly
    write("b5-tier8-trace", "stage-level diagnostic traces of the key cells (instrumented: never mixed with the performance runs)", [
        point(f"trace-{c}", "vllm_pipeline", "diagnostic", c, trace_cells, primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, trace="steps", tag=f"trace-{c}", timeout=3000)
        for c in ("cuda-metal", "metal-cuda", "cuda-cpu")], timeout=3000, campaign=14400)

    # Tier 6b: the stage-boundary transport of vllm-tbccl on its own (CUDA with CPU; the Metal boundary has its own transport class and is traced in tier 8 instead)
    def backend_point(name, orientation):
        mem = {"host-a": "cuda", "host-b": "host"}
        opts = {"dtype": "bfloat16", "max_model_len": MAX_LEN, "tag": name, "tokens": [1, 4, 12, 128, 512, 2000], "primary_tokens": 1, "warmup": 50, "iterations": 300,
                "phases": [{"name": "unused", "kind": "warmup"}]}
        return {"name": name, "benchmark": "vllm_backend", "operation": "pingpong", "sizes": [1], "memory_backend": mem, "orientations": [orientation], "options": opts, "timeout_s": 600, "repetitions": 3}
    write("b5-tier6b-backend", "vllm-tbccl stage-boundary ping-pong at the GroupCoordinator level (no model): CUDA with CPU, both rank orders, 3 repetitions", [
        backend_point("boundary-cuda-first", "forward"), backend_point("boundary-cpu-first", "reverse")], timeout=600, campaign=3600)


if __name__ == "__main__":
    main()
