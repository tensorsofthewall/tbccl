#!/usr/bin/env python3
"""Writes the B6 presets (Exo pipeline-parallel inference: MlxTbccl through exo-tbccl against MlxRing) next to this file. Run from the repository root:  python3 benchmarks/suite/configs/generate_b6.py

The presets are plain YAML with placeholders for the real addresses, paths and launcher (a git-ignored overlay fills them). Each workload point is one cluster lifecycle (start the nodes, place one
instance, load, run the ordered client phases, delete the instance, stop the nodes); the generator documents exactly which phases exist, in which order and with which seeds. Orientation
``forward`` runs the client and API on host-a; Exo chooses the stage order, so the placement that happened is recorded, never assumed.
"""
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL = "mlx-community/Qwen3-0.6B-8bit"
BACKENDS = ("MlxRing", "MlxTbccl")
PROMPTS = {  # items: how many repeated sentences follow the instruction; approx_tokens is a label, the measured prompt tokens come from the server's usage of every request
    "short": {"text": "Count from one to five in words.", "approx_tokens": 20},
    "p16": {"items": 0, "approx_tokens": 24},
    "p128": {"items": 6, "approx_tokens": 140},
    "p512": {"items": 24, "approx_tokens": 520},
}
MEMORY_MB = {"host-a": 5200, "host-b": 10800}  # exo's advertised-memory setting; it advertises host RAM, not VRAM, and would otherwise choose a placement the 8 GB GPU cannot hold

HEAD = '''# B6 preset: {desc}
# Physical (Thunderbolt) campaign: Exo pipeline parallelism (two nodes) between a Linux host (host-a: CUDA) and a macOS host (host-b: Metal), MlxTbccl through exo-tbccl {etbccl} against MlxRing.
# Real addresses, paths, interpreters and the launcher live in a git-ignored overlay; this file holds the workload matrix and the safety limits. Run `doctor --probe --allow-physical`
# and `--dry-run` first, then run tier by tier with --allow-physical. Results are local and git-ignored; performance numbers are never CI gates. Generated by generate_b6.py.
schema: tbccl-bench-config/1
name: {name}
description: "{desc}"
defaults:
  repetitions: {reps}
  timeout_s: {timeout}
  startup_wait_s: 30
  lease_s: 30
  term_grace_s: 30
  port_range: [<PORT_RANGE_START>, <PORT_RANGE_END>]
  failure_policy: {{on_failure: abort_run}}
  provenance: {{require_same_version: false, require_stamped: false}}
  health: {{strict: true, snapshot_each_point: true, max_load_fraction: 8.0}}
limits:
  max_processes: 8
  max_point_bytes: 8589934592
  max_total_bytes: {total}
  max_campaign_s: {campaign}
topology:
  kind: direct-link
  interconnect: thunderbolt4-ip      # a label for reports; TBCCL's transport is TCP over IPv4, never RDMA
  transport: tcp
  physical: true
hosts:
  host-a:                            # the machine the suite runs on
    launcher: {{kind: local}}
    address: <HOST_A_LINK_ADDRESS>
    interface: <HOST_A_LINK_INTERFACE>
    interfaces: {{link: <HOST_A_LINK_ADDRESS>}}
    executables: {{exo: <HOST_A_EXO>, exo_python: <HOST_A_EXO_PYTHON>, exo_bench_dir: <HOST_A_EXO_BENCH_DIR>, exo_home: <HOST_A_EXO_HOME>, exo_dashboard_dir: <HOST_A_EXO_DASHBOARD_DIR>, exo_lan_address: <HOST_A_LAN_ADDRESS>}}
    health_snapshot: true
    expect: {{mtu: <EXPECTED_MTU>}}
  host-b:                            # reached through a management-path launcher (never the data link)
    launcher: {{kind: prefix, argv: ["<REMOTE_LAUNCH_PREFIX>", "<REMOTE_HOST_NAME>"], shell_join: true}}
    python: <HOST_B_PYTHON>
    address: <HOST_B_LINK_ADDRESS>
    interface: <HOST_B_LINK_INTERFACE>
    interfaces: {{link: <HOST_B_LINK_ADDRESS>}}
    management_address: <HOST_B_MANAGEMENT_ADDRESS>   # checked: the controller must reach it through a different interface than the data link
    executables: {{exo: <HOST_B_EXO>, exo_python: <HOST_B_EXO_PYTHON>, exo_bench_dir: <HOST_B_EXO_BENCH_DIR>, exo_home: <HOST_B_EXO_HOME>, exo_dashboard_dir: <HOST_B_EXO_DASHBOARD_DIR>, exo_lan_address: <HOST_B_LAN_ADDRESS>}}
    health_script: <HOST_B_REPOSITORY>/scripts/tb4_health_snapshot.py
    expect: {{mtu: <EXPECTED_MTU>}}
'''


def j(x):
    return json.dumps(x, separators=(", ", ": "))


def ranks_block():
    return "ranks:\n  - {rank: 0, host: host-a, memory_backend: host, interface: link}\n  - {rank: 1, host: host-b, memory_backend: host, interface: link}\n"


def phase(name, kind, **kw):
    return {"name": name, "kind": kind, **kw}


def shuffled(cells, seed):
    cells = list(cells)
    random.Random(seed).shuffle(cells)
    return cells


def point(name, op, benchmark, backend, phases, *, orientation="forward", primary=None, tag=None, timeout=None, extra=None, reps=None, model=MODEL, prompts=None, load_timeout=900, single=None):
    opts = {"model_id": model, "backend": backend, "prompts": prompts or PROMPTS, "phases": phases, "memory_override_mb": MEMORY_MB, "load_timeout_s": load_timeout,
            "request_timeout_s": 300, "tag": tag or name}
    if primary:
        opts["primary"] = primary
    opts.update(extra or {})
    mem = {"host-a": "cuda", "host-b": "metal"} if not single else {single[0]: single[1]}
    wl = {"name": name, "benchmark": benchmark, "operation": op, "sizes": [1], "memory_backend": mem, "orientations": [orientation], "options": opts}
    if single:
        wl["rank_counts"] = [1]
        wl["rank_hosts"] = [single[0]]
    if timeout:
        wl["timeout_s"] = timeout
    if reps:
        wl["repetitions"] = reps
    return wl


def write(name, desc, workloads, *, reps=1, timeout=1800, total=8589934592, campaign=14400, etbccl="0.3.0"):
    text = HEAD.format(desc=desc, name=name, reps=reps, timeout=timeout, total=total, campaign=campaign, etbccl=etbccl) + ranks_block() + "workloads:\n"
    for wl in workloads:
        text += f"  - {j(wl)}\n"
    (HERE / f"{name}.yaml").write_text(text)
    print(name, len(workloads), "workloads")


GATE_PROMPTS = ("short", "p16", "p128", "p512")
GATE_CASES = [{"prompt": p, "max_tokens": n} for p in GATE_PROMPTS for n in (16, 64)]


def gate_phases(prefix="gate"):
    """Correctness gates against the single-device reference: sequential, repeated, after re-creating the instance, and cancellation with a follow-up. Concurrency gates come with the throughput tier."""
    return [
        phase("warm", "warmup", prompt="short", max_tokens=8, requests=2),
        phase(f"{prefix}-seq", "check", cases=GATE_CASES, conc=1, repeat=1),
        phase(f"{prefix}-repeat", "check", cases=[c for c in GATE_CASES if c["max_tokens"] == 16], conc=1, repeat=3),
        phase("recreate", "recreate"),
        phase(f"{prefix}-after-recreate", "check", cases=GATE_CASES, conc=1, repeat=1),
        phase(f"{prefix}-cancel", "cancel", prompt="p128", max_tokens=200, streams=4, complete_every=4, drop_after_events=4, settle_s=4,
              followup={"kind": "check", "cases": [c for c in GATE_CASES if c["max_tokens"] == 16], "conc": 1}),
    ]


def latency_cells(passes=2, per_cell=5, prompts=("p16", "p128", "p512"), outputs=(1, 16, 32, 64), seed=401):
    """Single-request latency cells: prompt length x output length at concurrency 1, every cell visited in each pass in a seeded shuffled order so slow drift does not line up with one cell."""
    cells = [(p, o) for p in prompts for o in outputs]
    out = []
    for k in range(passes):
        for p, o in shuffled(cells, seed + k):
            out.append(phase(f"lat-r{k + 1}-{p}-o{o}", "rounds", prompt=p, max_tokens=o, conc=1, requests=per_cell))
    return out


def latency_phases(seed=401):
    quick_gate = [c for c in GATE_CASES if c["max_tokens"] == 16 and c["prompt"] in ("p16", "p128")]
    return [phase("warm", "warmup", prompt="p128", max_tokens=8, requests=3), phase("gate", "check", cases=quick_gate, conc=1, repeat=1)] + latency_cells(seed=seed)


def concurrency_phases(levels=(1, 2, 4, 8), prompt="p128", tokens=32, passes=3, seed=501):
    """Closed-loop concurrency sweep. A correctness gate runs first at every level (independent streams, no cross-contamination of outputs, correct state afterwards), then ``passes`` passes
    over the levels in a seeded shuffled order, each level as rounds (all ``conc`` requests start together) and as a continuous loop (a worker issues its next request when the previous ends)."""
    quick = [c for c in GATE_CASES if c["max_tokens"] == 16 and c["prompt"] in ("short", "p16", "p128")]
    out = [phase("warm", "warmup", prompt=prompt, max_tokens=8, requests=3)]
    for c in levels:
        out.append(phase(f"gate-c{c}", "check", cases=quick, conc=c, repeat=3 if c > 1 else 1))
    for k in range(passes):
        for c in shuffled(list(levels), seed + k):
            out.append(phase(f"conc-r{k + 1}-c{c}-rounds", "rounds", prompt=prompt, max_tokens=tokens, conc=c, requests=max(8, 4 * c)))
            out.append(phase(f"conc-r{k + 1}-c{c}-cont", "continuous", prompt=prompt, max_tokens=tokens, conc=c, requests=max(24, 6 * c)))
    return out


def abba(n):
    """Backend order of n lifecycles (n a multiple of 4): A,B,B,A repeated, so each backend sees every position a lifecycle can have in the campaign (drift, caches, thermal state)."""
    return [("MlxRing", "MlxTbccl", "MlxTbccl", "MlxRing")[i % 4] for i in range(n)]


def main():
    # Tier 1: cluster discovery, placement, model load, one short request and an orderly shutdown, once per backend (the order is interleaved in later tiers; here it only proves the lifecycle)
    life = [phase("first-use", "warmup", prompt="short", max_tokens=8, requests=1)]
    write("b6-tier1-lifecycle", "Exo discovery, placement, model load, first request and shutdown, MlxRing and MlxTbccl", [
        point(f"life-{b.lower()}", "startup", "exo_lifecycle", b, life, primary={"phase": "first-use", "metric": "e2e"}) for b in BACKENDS], timeout=1500, campaign=7200)

    # Tier 2a: greedy single-device references (one node, MlxRing instance with min_nodes 1), then each reference checked against itself for run-to-run determinism
    ref_cases = GATE_CASES
    refs = [point(f"ref-{dev}", "gates", "exo_correctness", "MlxRing", [phase("ref", "reference", cases=ref_cases), phase("self-check", "check", cases=ref_cases, conc=1, repeat=1)],
                  primary={"phase": "self-check", "metric": "e2e"}, single=(host, dev), extra={"use_reference": False}) for host, dev in (("host-a", "cuda"), ("host-b", "metal"))]
    write("b6-tier2-reference", "single-device greedy references (Linux CUDA, Mac Metal) for the correctness gates, with a self-consistency check", refs, timeout=900, campaign=3600)
    # Tier 2b/3: the correctness gates of the two-node pipeline, one point per backend (MlxTbccl first: it is the integration under test; MlxRing proves the placement equivalence)
    write("b6-tier2-correctness", "two-node pipeline correctness against the CUDA reference: MlxTbccl and MlxRing, sequential, repeated, after re-creation, cancellation", [
        point(f"gates-{b.lower()}", "gates", "exo_correctness", b, gate_phases(), primary={"phase": "gate-seq", "metric": "e2e"}, timeout=1500) for b in ("MlxTbccl", "MlxRing")], timeout=1500, campaign=7200)

    # Tier 4: matched MlxRing / MlxTbccl single-request latency, 8 independent cluster lifecycles interleaved A,B,B,A,A,B,B,A. Exo chooses the stage order and the layer split
    # (the split follows the advertised memory); both are recorded per lifecycle and the analysis compares only lifecycles with the same placement.
    write("b6-tier4-latency", "matched MlxRing / MlxTbccl single-request latency: 3 prompt lengths x 4 output lengths, 2 passes, concurrency 1; 8 lifecycles interleaved A,B,B,A,A,B,B,A", [
        point(f"lat-{i + 1}-{b.lower()}", "single_request", "exo_latency", b, latency_phases(seed=401 + 10 * i), primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, tag=f"lat-{i + 1}-{b.lower()}", timeout=2400)
        for i, b in enumerate(abba(8))], timeout=2400, campaign=28800)

    # Tier 5: closed-loop concurrency 1/2/4/8 per backend (Exo's default limit is 8 concurrent requests; nothing beyond it is attempted), interleaved A,B,B,A
    write("b6-tier5-concurrency", "closed-loop concurrency 1/2/4/8 (p128/o32): gates at every level, then rounds and continuous loops over 3 passes; 4 lifecycles interleaved A,B,B,A", [
        point(f"conc-{i + 1}-{b.lower()}", "closed_loop", "exo_throughput", b, concurrency_phases(seed=501 + 10 * i), primary={"phase": "conc-r1-c8-cont", "metric": "e2e"}, tag=f"conc-{i + 1}-{b.lower()}",
              timeout=3600) for i, b in enumerate(abba(4))], timeout=3600, campaign=21600)

    # Tier 6: layer split, one variable at a time. Exo divides the layers by the advertised memory (OVERRIDE_MEMORY_MB, its own setting), so the Linux share of the 28 layers is changed by
    # the ratio of the two advertised values while everything else (backend MlxTbccl, workload, model) stays fixed. Exo still chooses the stage order per start; it is recorded and analysed
    # as a second factor, never assumed. Two lifecycles per split.
    splits = {4: (1760, 10800), 9: (5200, 10800), 14: (10800, 10800), 19: (22800, 10800)}
    order = [4, 9, 14, 19, 19, 14, 9, 4]
    cells = [phase("warm", "warmup", prompt="p128", max_tokens=8, requests=3), phase("gate", "check", cases=[c for c in GATE_CASES if c["max_tokens"] == 16 and c["prompt"] in ("p16", "p128")], conc=1)]
    cells += [phase(f"lat-r{k}-p128-o32", "rounds", prompt="p128", max_tokens=32, conc=1, requests=15) for k in (1, 2, 3)]
    cells += [phase(f"lat-r1-p16-o16", "rounds", prompt="p16", max_tokens=16, conc=1, requests=10), phase(f"lat-r1-p512-o16", "rounds", prompt="p512", max_tokens=16, conc=1, requests=10)]
    write("b6-tier6-placement", "layer split study (Linux share 4/9/14/19 of 28 layers via Exo's advertised-memory setting), MlxTbccl, p128/o32 plus two further cells; 8 lifecycles", [
        point(f"split-{n}-{i + 1}", "single_request", "exo_latency", "MlxTbccl", cells, primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, tag=f"split-{n}-{i + 1}", timeout=1800,
              extra={"memory_override_mb": {"host-a": splits[n][0], "host-b": splits[n][1]}}) for i, n in enumerate(order)], timeout=1800, campaign=21600)
    # Tier 7: instrumented runs (never mixed with the performance campaign): exo-tbccl's own trace through the diagnostic hook, same workload as the matching latency cell, both backends
    traced = [phase("warm", "warmup", prompt="p128", max_tokens=8, requests=3)] + [phase(f"lat-r{k}-p128-o32", "rounds", prompt="p128", max_tokens=32, conc=1, requests=15) for k in (1, 2)]
    write("b6-tier7-trace", "traced MlxTbccl and MlxRing lifecycles (exo-tbccl trace and CopyStats through the diagnostic hook), p128/o32; instrumented, reported separately", [
        point(f"trace-{i + 1}-{b.lower()}", "trace", "exo_stage_profile", b, traced, primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, tag=f"trace-{i + 1}-{b.lower()}", timeout=1800, extra={"trace": True})
        for i, b in enumerate(abba(4))], timeout=1800, campaign=14400)

    # Tier 8: the 27B 4-bit model (64 layers, ~15 GB) over the combined device memory. It fits no single device here, so the correctness reference is the MlxRing pipeline itself: lifecycle 1 records it,
    # the MlxTbccl lifecycles check against it (reference_file; copy the reference made by the first point before running the rest). Prompts are short: with the 8 GB CUDA stage holding 21 of the 64
    # layers a 138-token prompt ran out of memory in prefill (cudaMallocAsync) in the first attempt, the condition an earlier study had found above roughly 140-250 prompt tokens; an out-of-memory
    # condition is never retried. The last two points are single cautious probes at a 60-token prompt.
    big = "mlx-community/Qwen3.8-27B-4bit"
    # "Count from one to five" ends by itself after 11 tokens, so it cannot show 16-32 output tokens; "count30" keeps generating past 32 tokens
    cases27 = [{"prompt": "count30", "max_tokens": 16}, {"prompt": "count30", "max_tokens": 32}]
    timed27 = [phase("first", "rounds", prompt="count30", max_tokens=16, conc=1, requests=5), phase("gen32", "rounds", prompt="count30", max_tokens=32, conc=1, requests=5)]
    warm27 = phase("warm", "warmup", prompt="count30", max_tokens=8, requests=1)
    prompts27 = {"count30": {"text": "Count from one to thirty in words, separated by commas.", "approx_tokens": 26}, "p64": {"items": 2, "approx_tokens": 60}}
    big_opts = {"load_timeout_s": 1800, "request_timeout_s": 600}
    ref_file = ".local/b6/references/ref-27b-ring-count30.reference.json"
    pts = [point("big-1-ring-ref", "large", "exo_large_model", "MlxRing", [warm27, phase("ref", "reference", cases=cases27)] + timed27, model=big, prompts=prompts27, primary={"phase": "gen32", "metric": "tpot"},
                 tag="big-1-ring-ref", timeout=3600, load_timeout=1800, extra={**big_opts, "use_reference": False})]
    for i, bk in ((2, "MlxTbccl"), (3, "MlxTbccl"), (4, "MlxRing")):
        pts.append(point(f"big-{i}-{bk.lower()}", "large", "exo_large_model", bk, [warm27, phase("gate", "check", cases=cases27, conc=1)] + timed27, model=big, prompts=prompts27,
                         primary={"phase": "gen32", "metric": "tpot"}, tag=f"big-{i}-{bk.lower()}", timeout=3600, load_timeout=1800, extra={**big_opts, "reference_file": ref_file}))
    for i, bk in ((5, "MlxTbccl"), (6, "MlxRing")):
        pts.append(point(f"big-{i}-probe-p64-{bk.lower()}", "large", "exo_large_model", bk, [warm27, phase("p64-o32", "rounds", prompt="p64", max_tokens=32, conc=1, requests=3)], model=big, prompts=prompts27,
                         primary={"phase": "p64-o32", "metric": "tpot"}, tag=f"big-{i}-probe", timeout=3600, load_timeout=1800, extra={**big_opts, "use_reference": False}))
    write("b6-tier8-large", "Qwen3.8-27B-4bit over CUDA + Metal: MlxRing reference lifecycle, then MlxTbccl, MlxTbccl, MlxRing checked against it; short prompts, 16-32 output tokens; two 60-token probes", pts,
          timeout=3600, campaign=21600)
    # Tier 10: confirmation. Twelve independent lifecycles (six per backend) interleaved A,B,B,A,A,B,B,A,A,B,B,A of the key cells; the stage order is random per start, so the analysis is stratified by
    # the placement that actually happened and a stratum with fewer than two lifecycles per side is not compared.
    key = [phase("warm", "warmup", prompt="p128", max_tokens=8, requests=3), phase("gate", "check", cases=[c for c in GATE_CASES if c["max_tokens"] == 16 and c["prompt"] in ("p16", "p128")], conc=1)]
    key += [phase(f"lat-r{k}-p128-o32", "rounds", prompt="p128", max_tokens=32, conc=1, requests=10) for k in (1, 2, 3)]
    key += [phase("lat-r1-p512-o16", "rounds", prompt="p512", max_tokens=16, conc=1, requests=10), phase("lat-r1-p16-o64", "rounds", prompt="p16", max_tokens=64, conc=1, requests=10)]
    write("b6-tier10-confirm", "confirmation: 12 independent lifecycles interleaved A,B,B,A x3, key cells (p128/o32, p512/o16, p16/o64), concurrency 1", [
        point(f"confirm-{i + 1}-{bk.lower()}", "ab", "exo_transport_ab", bk, key, primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, tag=f"confirm-{i + 1}-{bk.lower()}", timeout=1800)
        for i, bk in enumerate(abba(12))], timeout=1800, campaign=28800)

    # Tier 9: optional exo-tbccl fast paths, an experimental tier kept apart from the baseline. Each variant changes exactly one setting of default MlxTbccl (the documented candidates:
    # receive-buffer reuse, asynchronous decode sends, a bounded poll before a blocking wait (Metal only), the Metal step-activity helper); the default MlxTbccl control and MlxRing run in the
    # same campaign, interleaved, so drift does not line up with one variant. Four rounds, each a seeded shuffle of the six arms. Every lifecycle runs the correctness gate (3x repeated) first;
    # the actual setting is recorded in the result. Nothing here changes a released default.
    variants = {"default": {}, "recv-reuse": {"EXO_TBCCL_RECV": "reuse"}, "async-send": {"EXO_TBCCL_ASYNC_SEND": "1"}, "wait-spin-5ms": {"EXO_TBCCL_WAIT_SPIN_MS": "5"},
                "activity-step": {"EXO_TBCCL_ACTIVITY_MODE": "step"}, "ring": None}
    fp_phases = [phase("warm", "warmup", prompt="p128", max_tokens=8, requests=3),
                 phase("gate", "check", cases=[c for c in GATE_CASES if c["max_tokens"] == 16 and c["prompt"] in ("p16", "p128")], conc=1, repeat=3)]
    fp_phases += [phase(f"lat-r{k}-p128-o32", "rounds", prompt="p128", max_tokens=32, conc=1, requests=10) for k in (1, 2, 3)]
    fp_phases += [phase("lat-r1-p512-o16", "rounds", prompt="p512", max_tokens=16, conc=1, requests=10), phase("lat-r1-p16-o64", "rounds", prompt="p16", max_tokens=64, conc=1, requests=10)]
    fp_points = []
    for rnd in range(4):
        for name in shuffled(list(variants), 900 + rnd):
            env = variants[name]
            backend = "MlxRing" if env is None else "MlxTbccl"
            extra = {"variant": "default" if env is None else name}
            if env:
                extra.update({"tier": "fastpath", "env": env})
            fp_points.append(point(f"fp-{rnd + 1}-{name}", "ab", "exo_transport_ab", backend, fp_phases, primary={"phase": "lat-r1-p128-o32", "metric": "tpot"}, tag=f"fp-{rnd + 1}-{name}",
                                   timeout=1800, extra=extra))
    write("b6-tier9-fastpath", "optional fast paths (one at a time) against default MlxTbccl and MlxRing, 4 interleaved rounds of 6 arms; experimental tier, baseline untouched", fp_points, timeout=1800, campaign=36000)


if __name__ == "__main__":
    main()
