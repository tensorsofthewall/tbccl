#!/usr/bin/env python3
"""Generate and verify release/wheels.json, the machine-readable inventory of the adapter wheels attached to the current stable GitHub Releases.

    gen_wheel_inventory.py --write     rebuild release/wheels.json from each release's SHA256SUMS (network) and release/ecosystem.json
    gen_wheel_inventory.py             offline: structure, agreement with ecosystem.json, filename/tag consistency
    gen_wheel_inventory.py --online    additionally: every recorded hash equals the release's SHA256SUMS, and every wheel URL downloads to that hash

Wheel filenames are never guessed: an entry exists only for a file named in a release's SHA256SUMS, and its python and platform tags are read from the
filename. Framework pins come from ecosystem.json (the one statement of current compatibility); this file records only what exists on each release.
"""
import argparse
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "release" / "wheels.json"
ECOSYSTEM = ROOT / "release" / "ecosystem.json"
# adapter name used by the installer -> (ecosystem.json key, wheel distribution name)
ADAPTERS = {"torch": ("torch_tbccl", "torch_tbccl"), "vllm": ("vllm_tbccl", "vllm_tbccl"), "exo": ("exo_tbccl", "exo_tbccl")}
WHEEL = re.compile(r"^(?P<dist>[A-Za-z0-9_]+)-(?P<version>[^-]+)-(?P<py>cp\d+)-(?P<abi>cp\d+)-(?P<plat>[^-]+)\.whl$")


def platform_of(tag):
    """Normalise a wheel platform tag (possibly dotted: compressed multi-tag) to one of the supported platforms."""
    parts = tag.split(".")
    if any(p.startswith("manylinux") and p.endswith("_x86_64") for p in parts):
        return {"platform": "linux_x86_64"}
    m = re.match(r"macosx_(\d+)_(\d+)_arm64$", tag)
    if m:
        return {"platform": "macos_arm64", "min_macos": f"{m.group(1)}.{m.group(2)}"}
    raise ValueError(f"unsupported platform tag {tag!r}")


def framework_of(key, eco):
    entry = eco[key]
    if key == "torch_tbccl":
        major_minor = entry["torch"]
        return {"name": "torch", "series": major_minor}
    if key == "vllm_tbccl":
        return {"name": "vllm", "exact": entry["vllm"]}
    return None


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def sums_url(repo, tag):
    return f"https://github.com/{repo}/releases/download/{tag}/SHA256SUMS"


def parse_sums(text):
    out = {}
    for line in text.splitlines():
        if line.strip():
            digest, name = line.split(None, 1)
            out[name.strip().lstrip("*")] = digest
    return out


def build(eco):
    adapters = {}
    for name, (key, dist) in ADAPTERS.items():
        e = eco[key]
        base = f"https://github.com/{e['repo']}/releases/download/{e['tag']}"
        sums = parse_sums(fetch(sums_url(e["repo"], e["tag"])).decode())
        wheels = []
        for fname in sorted(sums):
            m = WHEEL.match(fname)
            if not m:
                continue
            if m.group("dist") != dist or m.group("version") != e["version"]:
                raise SystemExit(f"{fname}: not {dist} {e['version']}")
            wheels.append({"filename": fname, "url": f"{base}/{fname}", "sha256": sums[fname], "python": m.group("py"), **platform_of(m.group("plat"))})
        if not wheels:
            raise SystemExit(f"{name}: no wheels in the release")
        adapters[name] = {"repo": e["repo"], "version": e["version"], "tag": e["tag"], "commit": e["commit"], "sums_url": sums_url(e["repo"], e["tag"]), "framework": framework_of(key, eco), "wheels": wheels}
    return {"schema_version": 1, "description": "Adapter wheels attached to the current stable releases (ecosystem.json). Generated by tools/gen_wheel_inventory.py from each release's SHA256SUMS; verified online in CI. Framework pins come from ecosystem.json.", "adapters": adapters}


def check_offline(inv, eco):
    problems = []
    if inv.get("schema_version") != 1:
        problems.append("schema_version must be 1")
    for name, (key, dist) in ADAPTERS.items():
        a = inv["adapters"].get(name)
        if a is None:
            problems.append(f"{name}: missing")
            continue
        e = eco[key]
        for field in ("repo", "version", "tag", "commit"):
            if a[field] != e[field]:
                problems.append(f"{name}.{field}: inventory {a[field]!r}, ecosystem.json {e[field]!r}")
        if a["framework"] != framework_of(key, eco):
            problems.append(f"{name}.framework: {a['framework']!r} does not match ecosystem.json")
        seen = set()
        for w in a["wheels"]:
            m = WHEEL.match(w["filename"])
            if not m or m.group("dist") != dist or m.group("version") != a["version"]:
                problems.append(f"{w['filename']}: not a {dist} {a['version']} wheel")
                continue
            if w["url"] != f"https://github.com/{a['repo']}/releases/download/{a['tag']}/{w['filename']}":
                problems.append(f"{w['filename']}: url does not name the recorded release")
            if not re.fullmatch(r"[0-9a-f]{64}", w["sha256"]):
                problems.append(f"{w['filename']}: sha256 is not 64 hex digits")
            if w["python"] != m.group("py") or {k: v for k, v in w.items() if k in ("platform", "min_macos")} != platform_of(m.group("plat")):
                problems.append(f"{w['filename']}: python/platform fields disagree with the filename")
            key2 = (w["python"], w["platform"])
            if key2 in seen:
                problems.append(f"{name}: two wheels for {key2}")
            seen.add(key2)
    return problems


def check_online(inv):
    problems = []
    for name, a in inv["adapters"].items():
        sums = parse_sums(fetch(a["sums_url"]).decode())
        listed = {n for n in sums if n.endswith(".whl")}
        recorded = {w["filename"] for w in a["wheels"]}
        if listed != recorded:
            problems.append(f"{name}: release has wheels {sorted(listed ^ recorded)} that the inventory does not (or vice versa)")
        for w in a["wheels"]:
            if sums.get(w["filename"]) != w["sha256"]:
                problems.append(f"{w['filename']}: inventory hash differs from the release's SHA256SUMS")
                continue
            got = hashlib.sha256(fetch(w["url"])).hexdigest()
            if got != w["sha256"]:
                problems.append(f"{w['filename']}: downloaded file hashes to {got}")
            else:
                print(f"ok: {w['filename']}")
    return problems


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--online", action="store_true")
    ap.add_argument("--file", default=str(INVENTORY))
    args = ap.parse_args()
    eco = json.loads(ECOSYSTEM.read_text())
    if args.write:
        Path(args.file).write_text(json.dumps(build(eco), indent=2) + "\n")
        print(f"wrote {args.file}")
    inv = json.loads(Path(args.file).read_text())
    problems = check_offline(inv, eco)
    if args.online:
        problems += check_online(inv)
    for p in problems:
        print(f"INTEGRITY FAILURE: {p}")
    if problems:
        sys.exit(1)
    print(f"wheel inventory ({'online' if args.online else 'offline'}): OK")


if __name__ == "__main__":
    main()
